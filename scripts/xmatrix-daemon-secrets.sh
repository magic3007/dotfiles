#!/usr/bin/env bash
# Make the xmatrix daemon — and every agent run it spawns — carry the user's
# secrets environment.
#
# Why
# ---
# xmatrix starts agent runs from its systemd --user daemon and hands the harness
# the daemon's own environment plus XMATRIX_*. ~/.common_shell_setup_local.sh is
# never sourced, so credentials that exist only as environment variables are
# absent. omp then resolves a key reference to the *variable name* and sends that
# as the API key (upstream: 401 "The API key format is incorrect"); codex
# `env_key` providers fail the same way.
#
# `xmatrix agent add --runtime <wrapper>` does NOT help: xmatrix 1.0.587 ignores
# the runtime override for harness runs (verified with --runtime /bin/echo — the
# run still started omp).
#
# What this does
# --------------
# Writes a systemd drop-in that re-execs the daemon under `bash -c`, sourcing the
# secrets file first, so the daemon environment — and therefore every agent run —
# carries the keys. The drop-in survives `xmatrix setup daemon`, which rewrites
# only the main unit. Secrets keep living in exactly one file.
#
# Usage: scripts/xmatrix-daemon-secrets.sh [--restart]
#   --restart  also restart the daemon (needed once, and after key changes)
set -euo pipefail

dropin_dir="$HOME/.config/systemd/user/xmatrix-daemon.service.d"
dropin="$dropin_dir/10-secrets-env.conf"
secrets="${HARNESS_ENV_FILE:-$HOME/.common_shell_setup_local.sh}"
daemon_bin="${XMATRIX_DAEMON_BIN:-$(command -v xmatrix || true)}"

if [ -z "$daemon_bin" ] || [ ! -x "$daemon_bin" ]; then
    echo "xmatrix not installed; nothing to do" >&2
    exit 0
fi
if [ ! -r "$secrets" ]; then
    echo "no readable secrets file ($secrets); nothing to do" >&2
    exit 0
fi
if ! command -v systemctl >/dev/null 2>&1; then
    echo "systemctl unavailable; this hook is Linux-only" >&2
    exit 0
fi

mkdir -p "$dropin_dir"
tmp="$(mktemp)"
cat > "$tmp" <<EOF
[Service]
# Generated by dotfiles/scripts/xmatrix-daemon-secrets.sh — do not edit.
# Sources $secrets before starting the daemon so agent runs inherit the
# provider credentials that only exist as environment variables.
ExecStart=
ExecStart=/bin/bash -c 'set -a; . "\$HOME/.common_shell_setup_local.sh"; set +a; exec ${daemon_bin} daemon'
EOF

if cmp -s "$tmp" "$dropin"; then
    rm -f "$tmp"
else
    chmod 0644 "$tmp"
    mv "$tmp" "$dropin"
    echo "wrote $dropin"
fi

systemctl --user daemon-reload

if [ "${1:-}" = "--restart" ]; then
    systemctl --user restart xmatrix-daemon
    echo "restarted xmatrix-daemon"
fi
